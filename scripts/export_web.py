"""Export the Python patterns and test samples for the browser version.

The free web page (docs/, served by GitHub Pages) runs the same rules in
JavaScript, directly on the user's phone or computer. Run this script after
editing app/analyzer/patterns.py or tests/samples.py:

    python scripts/export_web.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.analyzer import patterns  # noqa: E402
from tests import samples  # noqa: E402

data = {
    "textSignals": [
        {"id": sid, "weight": w, "patterns": pats, "reason": why}
        for sid, w, pats, why in patterns.TEXT_SIGNALS
    ],
    "familyWords": patterns.FAMILY_WORDS,
    "brands": patterns.BRANDS,
    "shorteners": sorted(patterns.URL_SHORTENERS),
    "suspiciousTlds": sorted(patterns.SUSPICIOUS_TLDS),
    "freeWebmails": sorted(patterns.FREE_WEBMAILS),
    "confusables": patterns.CONFUSABLES,
    "phoneRe": patterns.PHONE_RE,
    "callWords": patterns.CALL_WORDS,
    "supportWords": patterns.SUPPORT_WORDS,
    "genericSender": patterns.GENERIC_SENDER,
}

out = ROOT / "docs" / "patterns.js"
out.write_text(
    "// GENERATED by scripts/export_web.py from app/analyzer/patterns.py. Do not edit.\n"
    "window.VA_PATTERNS = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
    encoding="utf-8",
)

samples_out = ROOT / "tests" / "web" / "samples.json"
samples_out.parent.mkdir(exist_ok=True)
samples_out.write_text(
    json.dumps({"scams": samples.SCAMS, "legit": samples.LEGIT}, ensure_ascii=False, indent=1),
    encoding="utf-8",
)
print(f"wrote {out.relative_to(ROOT)} and {samples_out.relative_to(ROOT)}")
